"""Builds the water-rivers junction map (docs/projects/RIVERS.md, the render checks of PR B): a river, a lake, a river
and the sea in one line, for looking at the places where a sloped surface meets a flat one.

    python make_junction_map.py <base map folder> <output maps folder>

for example `make_junction_map.py "<game>/maps/SCMP_012" "<vault>/maps"`, which writes
`<vault>/maps/faf_re_waterrivers_junction/` (scmap, scenario, save, script). The map is made from the base map each time;
nothing binary is kept in the repo. It shares the helpers of make_map.py (the river carving, the plateau).

The plateau is the one of make_map.py; on it, from west to east along z = 100:

- river D1 (x 30 .. 98): a river that falls from 44 to 33 (the bed 4 under the surface);
- the lake L (a disc of radius 22 around (120, 100), flat at 33, bed 27): D1 ends at its west shore at its level, D2 starts at
  its east shore, so the surface of the river meets the surface of the lake edge to edge;
- river D2 (x 142 .. 214): falls from 33 to 27 and ends in the bay;
- the sea (level 27, the whole map's): a bay dug at the east end of the plateau (bed 14), where D2 reaches it at the
  sea's level. The map has no other water.

Nothing moves on it and it has no checks: `1p-waterrivers-main.yaml` is the sim test, this map is for frames.
"""
import importlib.util
import math
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "water-levels"))
from scmap import ScMap  # noqa: E402

_spec = importlib.util.spec_from_file_location("waterrivers_make_map", os.path.join(HERE, "make_map.py"))
rv = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(rv)
wl = rv.wl

NAME = "faf_re_waterrivers_junction"
SEA = 27.0
LAKE = (120.0, 100.0, 22.0)  # x, z, radius
LAKE_LEVEL = 33.0

# (x, z, Level, HalfWidth, Fall below or None)
RIVER_D1 = [
    (30, 100, 44.0, 6, None),
    (60, 94, 41.0, 6, None),
    (84, 98, 36.5, 6, None),
    (100, 100, 33.0, 6, None),
]
RIVER_D2 = [
    (140, 100, 33.0, 6, None),
    (166, 104, 31.0, 7, None),
    (190, 100, 28.5, 8, None),
    (214, 100, 27.0, 8, None),
]


def lake_outline(x, z, r):
    return wl.ellipse(x, z, r, r, 8)


def lua_lake(name, centre, level):
    outline = ", ".join("{ %g, %g }" % p for p in lake_outline(centre[0], centre[1], centre[2]))
    return ("{ Name = '%s', Elevation = %g, FillTo = %g, Seed = { %g, %g }, Outline = { %s } }"
            % (name, level, level, centre[0], centre[1], outline))


def build(base_dir, out_root):
    base = os.path.basename(os.path.normpath(base_dir))
    scmap = ScMap(open(os.path.join(base_dir, base + ".scmap"), "rb").read())
    terrain = wl.Terrain(scmap)

    plateau = [(10, 30), (125, 24), (245, 30), (250, 100), (245, 170), (125, 176), (10, 170), (5, 100)]
    terrain.raise_to(plateau, rv.PLATEAU, 12.0)

    # the rivers: the bed 4 under the surface
    bed = lambda level, x: level - 4.0
    rv.carve(terrain, RIVER_D1, bed, 8.0)
    rv.carve(terrain, RIVER_D2, bed, 8.0)
    # the lake: a disc, the bed 6 under its surface, rising to the plateau over 8 units
    terrain.dig_to(lake_outline(*LAKE), LAKE_LEVEL - 6.0, 8.0)
    # the bay: the sea's basin at the end of the plateau, the bed 13 under the sea
    bay = wl.ellipse(236.0, 100.0, 30.0, 34.0, 8)
    terrain.dig_to(bay, SEA - 13.0, 10.0)

    scmap.set_heights(terrain.words())
    scmap.set_water(True, SEA, SEA - 2.5, SEA - 15.0)

    out_dir = os.path.join(out_root, NAME)
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, NAME + ".scmap"), "wb") as f:
        f.write(scmap.data)

    scenario = open(os.path.join(base_dir, base + "_scenario.lua"), encoding="latin-1").read()
    scenario = scenario.replace("/maps/%s/%s" % (base, base), "/maps/%s/%s" % (NAME, NAME))
    scenario = re.sub(r"name\s*=\s*'[^']*'", "name = 'FAF RE water rivers junction'", scenario, count=1)
    # rivers first: the lowest body number owns a vertex they share with the lake
    table = "    WaterBodies = {\n" + "".join("        %s,\n" % b for b in (
        rv.lua_river("D1", RIVER_D1, 44.0), rv.lua_river("D2", RIVER_D2, 33.0),
        lua_lake("L", LAKE, LAKE_LEVEL))) + "    },\n"
    scenario = re.sub(r"(ScenarioInfo\s*=\s*\{\n)", lambda m: m.group(1) + table, scenario, count=1)
    if "WaterBodies" not in scenario or "/maps/%s/" % NAME not in scenario:
        raise SystemExit("could not place WaterBodies in the scenario or point it at the new map files")
    with open(os.path.join(out_dir, NAME + "_scenario.lua"), "w", encoding="latin-1", newline="\n") as f:
        f.write("-- Generated by faf-re tools/scenarios/water-rivers/make_junction_map.py from %s.\n" % base)
        f.write(scenario)
    shutil.copyfile(os.path.join(base_dir, base + "_save.lua"), os.path.join(out_dir, NAME + "_save.lua"))
    with open(os.path.join(out_dir, NAME + "_script.lua"), "w", encoding="latin-1", newline="\n") as f:
        f.write("-- faf_re_waterrivers_junction: no checks, the map is for frames (tools/scenarios/water-rivers/make_junction_map.py)\n")
    print("RESULT wrote %s: rivers D1 and D2, a lake and a sea, terrain %.2f..%.2f" % (out_dir, min(terrain.z), max(terrain.z)))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    build(sys.argv[1], sys.argv[2])
